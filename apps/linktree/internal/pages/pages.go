// Package pages holds the business rules of the link pages: what a page, a link and
// a group are, and how they are validated. It does no I/O.
package pages

// Themes known by the front (web/src/themes). The order is the one shown in the admin.
var Themes = []string{"zazi", "nuit", "papier", "neon", "pop"}

// Accents known by the front: each theme turns them into concrete colors.
var Accents = []string{"violet", "bleu", "cyan", "vert", "ambre", "orange", "rose", "neutre"}

// Defaults of a new page.
const (
	DefaultTheme  = "zazi"
	DefaultAccent = "violet"
)

// Kind tells a link from a group.
type Kind string

const (
	KindLink  Kind = "link"
	KindGroup Kind = "group"
)

// Visual is the picture of a page avatar or of an item: an uploaded image, a
// coolshapes shape, or nothing. At most one of ImageID and Shape is set.
type Visual struct {
	ImageID string // UUID of an uploaded image
	Shape   string // shape identifier, e.g. "star-1"
	// Dimensions of the image, filled when a page is loaded (the browser needs them
	// to reserve the space before the image arrives). Ignored when saving.
	Width, Height int
}

// IsZero reports whether there is no visual.
func (v Visual) IsZero() bool {
	return v.ImageID == "" && v.Shape == ""
}

// Page is the full document edited in the admin: settings and items.
type Page struct {
	ID          string
	Slug        string
	Title       string
	Description string
	Avatar      Visual
	Theme       string
	Accent      string
	Published   bool
	Listed      bool
	Version     int // incremented on each save (optimistic locking)
	Items       []Item
}

// Item is a link or a group. Groups hold links in Links; links have no Links.
type Item struct {
	ID            string // UUID generated by the admin client
	Kind          Kind
	Title         string
	Subtitle      string // groups only
	URL           string // links only
	Visual        Visual
	OpenByDefault bool // groups only
	Published     bool
	Links         []Item // groups only
}

// Summary describes a page in the admin list and in the public index.
type Summary struct {
	ID          string
	Slug        string
	Title       string
	Description string
	Avatar      Visual
	Published   bool
	Listed      bool
	LinkCount   int
}

// Visible returns a copy of the page without draft items, nor groups left without
// any visible link: what a visitor may see. Drafts never reach the browser.
func (p Page) Visible() Page {
	visible := p
	visible.Items = nil
	for _, it := range p.Items {
		if !it.Published {
			continue
		}
		if it.Kind == KindGroup {
			links := make([]Item, 0, len(it.Links))
			for _, l := range it.Links {
				if l.Published {
					links = append(links, l)
				}
			}
			if len(links) == 0 {
				continue
			}
			it.Links = links
		}
		visible.Items = append(visible.Items, it)
	}
	return visible
}
